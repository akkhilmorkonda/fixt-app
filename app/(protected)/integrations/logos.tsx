const GENERIC: Partial<Record<ConnectorKind, IconName>> = {
  mes: "route",
  plm: "note",
  erp: "tag",
  field_returns: "undo",
};

const SIZES = { sm: "h-8 w-8 rounded-lg", md: "h-10 w-10 rounded-xl" } as const;

export function ConnectorLogo({ kind, size = "md" }: { kind: string; size?: keyof typeof SIZES }) {
  const box = `flex shrink-0 items-center justify-center border ${SIZES[size]}`;
  const glyph = size === "sm" ? "h-4 w-4" : "h-5 w-5";
  const mark = MARKS[kind as ConnectorKind];
  if (mark) {
    return (
      <span className={`${box} ${mark.tile ?? "border-zinc-200 bg-white"}`}>
        <svg viewBox={mark.box} aria-hidden="true" className={glyph} fill={mark.color} fillRule="evenodd">
          {mark.paths.map((p, i) => (
            <path key={i} d={p.d} fill={p.fill} />
          ))}
        </svg>
      </span>
    );
  }
  // TestStand: NI's mark isn't in Simple Icons, so a monogram in its place.
  if (kind === "teststand") {
    return <span className={`${box} border-[#1a1a1a] bg-[#1a1a1a] font-heading text-[11px] font-bold tracking-tight text-white`}>NI</span>;
  }
  if (kind === "csv") {
    return (
      <span className={`${box} border-emerald-200 bg-emerald-50 text-emerald-700`}>
        <svg viewBox="0 0 16 16" fill="none" stroke="currentColor" strokeWidth="1.4" strokeLinejoin="round" aria-hidden="true" className={glyph}>
          <rect x="2.25" y="2.75" width="11.5" height="10.5" rx="1" />
          <path d="M2.25 6.25h11.5M2.25 9.75h11.5M6.25 2.75v10.5" />
        </svg>
      </span>
    );
  }
  return (
    <span className={`${box} border-zinc-200 bg-zinc-50 text-zinc-600`}>
      <Icon name={GENERIC[kind as ConnectorKind] ?? "plug"} className={glyph} />
    </span>
  );
}
